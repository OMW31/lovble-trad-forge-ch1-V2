function translateText(text) {
  let result = text;
  for (const [pattern, replacement] of PHRASE_TRANSLATIONS) {
    result = result.replace(pattern, replacement);
  }
  return result;
}

function translateChoices(choices) {
  return choices.map(c => ({
    id: c.id,
    label: translateText(c.label),
  }));
}

async function main() {
  // Fetch all FR questions from both tables
  const { data: partA, error: errA } = await supabase
    .from("question_bank_part_a")
    .select("question_key, lesson_id, difficulty, prompt, choices, correct_id, explanation")
    .eq("is_active", true);
  
  const { data: partB, error: errB } = await supabase
    .from("question_bank_part_b")
    .select("question_key, lesson_id, difficulty, prompt, choices, correct_id, explanation, widget, visual_id")
    .eq("is_active", true);

  if (errA || errB) {
    console.error("Fetch error:", errA?.message, errB?.message);
    process.exit(1);
  }

  console.log(`Fetched ${partA.length} Part A + ${partB.length} Part B questions`);

  // Generate EN translations
  const translations = [];
  
  for (const q of partA) {
    translations.push({
      question_key: q.question_key,
      part: "A",
      locale: "en",
      prompt: translateText(q.prompt),
      choices: translateChoices(q.choices),
      explanation: translateText(q.explanation),
    });
  }
  
  for (const q of partB) {
    translations.push({
      question_key: q.question_key,
      part: "B",
      locale: "en",
      prompt: translateText(q.prompt),
      choices: translateChoices(q.choices),
      explanation: translateText(q.explanation),
    });
  }

  console.log(`Generated ${translations.length} EN translations`);

  // Save to file for inspection
  writeFileSync("en-translations.json", JSON.stringify(translations, null, 2));
  console.log("Saved to en-translations.json");

  // Insert in batches of 20
  let inserted = 0;
  for (let i = 0; i < translations.length; i += 20) {
    const batch = translations.slice(i, i + 20);
    const { error } = await supabase
      .from("question_translations")
      .upsert(batch, { onConflict: "question_key,part,locale" });
    
    if (error) {
      console.error(`Batch ${i}-${i + batch.length} error:`, error.message);
    } else {
      inserted += batch.length;
      console.log(`Inserted batch ${i}-${i + batch.length} (${inserted}/${translations.length})`);
    }
  }

  console.log(`Done! Total inserted: ${inserted}`);
}

main().catch(e => { console.error(e); process.exit(1); });
